class LanguageManager {
    constructor() {
        this.currentLanguage = localStorage.getItem('selectedLanguage') || 'es';
        this.init();
    }

    init() {
        this.applyTranslations();
        this.setupLanguageSelectors();
        this.updateLanguageSelectorUI();
    }

    setupLanguageSelectors() {
        // Botones ES / EN en el header
        document.querySelectorAll('[data-language]').forEach(element => {
            element.addEventListener('click', (e) => {
                e.preventDefault();
                this.changeLanguage(element.getAttribute('data-language'));
            });
        });

        // Select desplegable (compatibilidad hacia atrás)
        const headerSelector = document.getElementById('language-select-header');
        if (headerSelector) {
            headerSelector.addEventListener('change', (e) => {
                this.changeLanguage(e.target.value);
            });
        }

        const mobileSelector = document.getElementById('language-select');
        if (mobileSelector) {
            mobileSelector.addEventListener('change', (e) => {
                this.changeLanguage(e.target.value);
            });
        }
    }

    changeLanguage(language) {
        if (language === 'spanish') language = 'es';
        if (language === 'english') language = 'en';

        this.currentLanguage = language;
        localStorage.setItem('selectedLanguage', language);

        this.applyTranslations();
        this.updateLanguageSelectorUI();
    }

    applyTranslations() {
        const lang = this.currentLanguage;

        // Traducir texto de elementos con data-translate
        document.querySelectorAll('[data-translate]').forEach(element => {
            const key = element.getAttribute('data-translate');
            if (translations[lang] && translations[lang][key]) {
                element.textContent = translations[lang][key];
            }
        });

        // Traducir HTML de elementos con data-translate-html
        document.querySelectorAll('[data-translate-html]').forEach(element => {
            const key = element.getAttribute('data-translate-html');
            if (translations[lang] && translations[lang][key]) {
                element.innerHTML = translations[lang][key];
            }
        });

        // Traducir placeholders
        document.querySelectorAll('[data-translate-placeholder]').forEach(element => {
            const key = element.getAttribute('data-translate-placeholder');
            if (translations[lang] && translations[lang][key]) {
                element.placeholder = translations[lang][key];
            }
        });

        // Traducir atributos title
        document.querySelectorAll('[data-translate-title]').forEach(element => {
            const key = element.getAttribute('data-translate-title');
            if (translations[lang] && translations[lang][key]) {
                element.title = translations[lang][key];
            }
        });

        // Actualizar atributo lang del HTML
        document.documentElement.lang = lang;

        // Disparar evento personalizado
        const event = new CustomEvent('languageChanged', { detail: { language: lang } });
        document.dispatchEvent(event);
    }

    updateLanguageSelectorUI() {
        const lang = this.currentLanguage;

        // Activar/desactivar botones ES / EN
        document.querySelectorAll('[data-language]').forEach(btn => {
            const btnLang = btn.getAttribute('data-language');
            if (btnLang === lang) {
                btn.classList.add('lang-btn--active');
                btn.setAttribute('aria-pressed', 'true');
            } else {
                btn.classList.remove('lang-btn--active');
                btn.setAttribute('aria-pressed', 'false');
            }
        });

        // Compatibilidad con selectores tipo <select>
        const headerSelector = document.getElementById('language-select-header');
        if (headerSelector) headerSelector.value = lang;

        const mobileSelector = document.getElementById('language-select');
        if (mobileSelector) mobileSelector.value = lang;
    }

    getTranslation(key) {
        return translations[this.currentLanguage]?.[key] || key;
    }
}

// Inicializar cuando el DOM esté listo
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        window.languageManager = new LanguageManager();
    });
} else {
    window.languageManager = new LanguageManager();
}
